"""CSV / JSONL / standalone-HTML exports of a run."""
from __future__ import annotations
import csv
import html
import io
import json

from .analysis import COND_LABEL


def rows_csv(rows: list) -> str:
    conds = []
    for r in rows:
        for c in r["answers"]:
            if c not in conds:
                conds.append(c)
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["qid", "lang", "gold", *conds, "roman_margin"])
    for r in rows:
        w.writerow([r["qid"], r["lang"], r["gold"], *[r["answers"].get(c) or "" for c in conds], (r.get("margins") or {}).get("roman", "")])
    return buf.getvalue()


def rows_jsonl(rows: list) -> str:
    return "\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n"


def report_html(meta: dict, rep: dict) -> str:
    e = html.escape
    v = rep.get("verdict") or {}
    colour = {"good": "#1a7f4b", "warn": "#b36b00", "bad": "#b3261e"}.get(v.get("level"), "#444")
    acc = "".join(
        f"<tr><td>{e(COND_LABEL.get(c, c))}</td><td>{a['acc']}%</td><td>{a['lo']}–{a['hi']}%</td><td>{a['n']}</td></tr>"
        for c, a in rep.get("accuracy", {}).items() if a)
    fnd = "".join(f"<li><b>{e(f['title'])}.</b> {e(f['text'])}</li>" for f in rep.get("findings", []))
    return f"""<!doctype html><meta charset="utf-8"><title>Vartani report – {e(meta['name'])}</title>
<style>body{{font:16px/1.55 system-ui;max-width:820px;margin:2rem auto;padding:0 1rem;color:#1b1b1f}}
table{{border-collapse:collapse;width:100%}}td,th{{border-bottom:1px solid #ddd;padding:.4rem .6rem;text-align:left}}
.v{{font-size:1.6rem;font-weight:700;color:{colour}}}li{{margin:.5rem 0}}small{{color:#666}}</style>
<h1>Vartani report</h1><p><b>{e(meta['name'])}</b> · model: {e(str(meta.get('model_label')))} · {rep.get('n_items')} items</p>
<p class="v">{e(v.get('label',''))}</p><p>{e(v.get('summary',''))}</p>
<h2>Accuracy by condition (chance = 25%)</h2><table><tr><th>Condition</th><th>Accuracy</th><th>95% CI</th><th>n</th></tr>{acc}</table>
<h2>Findings</h2><ul>{fnd}</ul>
<p><small>Generated by Vartani. Intervals are Wilson 95%; paired tests are exact McNemar; guessing test is exact binomial.</small></p>"""
